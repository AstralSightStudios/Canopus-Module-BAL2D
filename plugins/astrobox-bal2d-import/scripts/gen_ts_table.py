#!/usr/bin/env python3
"""Regenerates src/ts_chars.txt (Traditional -> Simplified, one character each) from OpenCC's
data/dictionary/TSCharacters.txt (Apache-2.0, https://github.com/BYVoid/OpenCC).

Usage: gen_ts_table.py TSCharacters.txt [commit]  (writes src/ts_chars.txt next to this script)
Each line of the output is a traditional character followed by the first simplified candidate;
lines are sorted by code point and characters that convert to themselves are left out.
"""
import sys
from pathlib import Path


def main():
    src = Path(sys.argv[1])
    commit = sys.argv[2] if len(sys.argv) > 2 else "master"
    pairs = {}
    for line in src.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, _, values = line.partition("\t")
        first = values.split(" ")[0] if values else ""
        if len(key) != 1 or len(first) != 1 or key == first:
            continue
        pairs.setdefault(key, first)
    out = Path(__file__).resolve().parent.parent / "src" / "ts_chars.txt"
    header = [
        "# Traditional -> Simplified Chinese, one character each: the first candidate of every line of",
        "# OpenCC data/dictionary/TSCharacters.txt (https://github.com/BYVoid/OpenCC, commit " + commit + ").",
        "# Copyright (c) the OpenCC contributors, licensed under the Apache License 2.0",
        "# (http://www.apache.org/licenses/LICENSE-2.0). Generated by scripts/gen_ts_table.py.",
    ]
    body = [k + v for k, v in sorted(pairs.items(), key=lambda kv: ord(kv[0]))]
    out.write_text("\n".join(header + body) + "\n", encoding="utf-8")
    print(f"{len(body)} pairs -> {out}")


if __name__ == "__main__":
    main()
